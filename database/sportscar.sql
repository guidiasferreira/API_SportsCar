CREATE DATABASE IF NOT EXISTS SPORTSCAR;

USE SPORTSCAR;

DROP TABLE IF EXISTS GASTOS;
DROP TABLE IF EXISTS VEICULOS;

CREATE TABLE IF NOT EXISTS VEICULOS (
  ID_VEICULO INT AUTO_INCREMENT,
  MARCA VARCHAR(50) NOT NULL,
  MODELO VARCHAR(80) NOT NULL,
  ANO_FABRICACAO INT NOT NULL,
  POTENCIA_CV INT NOT NULL,
  PLACA VARCHAR(8) NULL UNIQUE,
  CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  
  CONSTRAINT PK_VEICULOS PRIMARY KEY (ID_VEICULO),
  CONSTRAINT UQ_VEICULOS_PLACA UNIQUE (PLACA),
  CONSTRAINT CHK_ANO CHECK (ANO_FABRICACAO BETWEEN 1950 AND 2100),
  CONSTRAINT CHK_POTENCIA CHECK (POTENCIA_CV > 0)
  
) ENGINE = InnoDB;

CREATE TABLE IF NOT EXISTS GASTOS (
  ID_GASTO INT AUTO_INCREMENT,
  ID_VEICULO  INT NOT NULL,
  TIPO ENUM('manutencao', 'abastecimento', 'seguro', 'ipva', 'licenciamento', 'estacionamento', 'outros') NOT NULL,
  DESCRICAO VARCHAR(255) NULL,
  VALOR DECIMAL(10, 2) NOT NULL,
  DATA_GASTO  DATE NOT NULL,
  KM INT NOT NULL,
  CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  
  CONSTRAINT PK_GASTOS PRIMARY KEY (ID_GASTO),
  CONSTRAINT FK_GASTOS_VEICULO FOREIGN KEY (ID_VEICULO) REFERENCES VEICULOS (ID_VEICULO) ON DELETE CASCADE,
  CONSTRAINT CHK_VALOR CHECK (VALOR > 0),
  CONSTRAINT CHK_KM CHECK (KM IS NULL OR KM >= 0),
  
  INDEX IDX_GASTOS_VEICULO_DATA (ID_VEICULO, DATA_GASTO)
  
) ENGINE = InnoDB;

